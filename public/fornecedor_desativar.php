<?php

require_once __DIR__ . '/../includes/auth.php';
require_once __DIR__ . '/../config/database.php';

/*
|--------------------------------------------------------------------------
| VERIFICA ID
|--------------------------------------------------------------------------
*/

$id = (int) ($_POST['id'] ?? 0);

if ($id <= 0) {
    header('Location: fornecedor.php');
    exit;
}


/*
|--------------------------------------------------------------------------
| DESATIVA O FORNECEDOR
|--------------------------------------------------------------------------
*/

try {

    /*
    |--------------------------------------------------------------------------
    | BUSCA O FORNECEDOR
    |--------------------------------------------------------------------------
    */

    $sql = $pdo->prepare("
        SELECT id, nome
        FROM fornecedor
        WHERE id = ?
        LIMIT 1
    ");

    $sql->execute([$id]);

    $fornecedor = $sql->fetch(PDO::FETCH_ASSOC);


    /*
    |--------------------------------------------------------------------------
    | VERIFICA SE EXISTE
    |--------------------------------------------------------------------------
    */

    if (!$fornecedor) {

        header('Location: fornecedor.php');
        exit;
    }


    /*
    |--------------------------------------------------------------------------
    | DESATIVA
    |--------------------------------------------------------------------------
    |
    | IMPORTANTE:
    | A coluna correta é "ativa"
    |
    */

    $sql = $pdo->prepare("
        UPDATE fornecedor
        SET ativa = 0
        WHERE id = ?
    ");

    $sql->execute([$id]);


    /*
    |--------------------------------------------------------------------------
    | VOLTA PARA A LISTA
    |--------------------------------------------------------------------------
    */

    header('Location: fornecedor.php');
    exit;


} catch (PDOException $e) {

    /*
    |--------------------------------------------------------------------------
    | EM CASO DE ERRO
    |--------------------------------------------------------------------------
    */

    die(
        'Erro ao desativar fornecedor: ' .
        $e->getMessage()
    );
}